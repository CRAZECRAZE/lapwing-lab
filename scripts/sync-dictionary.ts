import { execFileSync } from 'node:child_process'
import { cpSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

export const UPSTREAM_URL = 'https://github.com/aerickt/plover-lapwing-aio'
export const DEFAULT_COMMIT = '4ac5d53cf039a2b1f4c484456663c85e7df4e859'
export const DICTIONARY_FILES: readonly string[] = [
  'lapwing-base.json',
  'lapwing-uk-additions.json',
  'lapwing-proper-nouns.json',
  'lapwing-numbers.json',
  'lapwing-commands.json',
  'lapwing-semi-modal-movement.json',
]

const root = join(import.meta.dirname, '..')
const dest = join(root, 'content', 'lapwing-dictionary')

function git(cwd: string, ...args: string[]): void {
  execFileSync('git', args, { cwd, stdio: 'inherit' })
}

export function syncDictionary(commit: string = DEFAULT_COMMIT): void {
  if (!/^[0-9a-f]{40}$/.test(commit)) {
    throw new Error(`Expected a full 40-hex commit hash, got "${commit}"`)
  }
  const tmp = mkdtempSync(join(tmpdir(), 'lapwing-dictionary-'))
  try {
    git(tmp, 'init', '--quiet')
    git(tmp, 'fetch', '--quiet', '--depth', '1', UPSTREAM_URL, commit)
    git(tmp, '-c', 'advice.detachedHead=false', 'checkout', '--quiet', 'FETCH_HEAD')

    rmSync(dest, { recursive: true, force: true })
    mkdirSync(dest, { recursive: true })
    for (const file of DICTIONARY_FILES) {
      cpSync(join(tmp, 'plover_lapwing', 'dictionaries', file), join(dest, file))
    }
    cpSync(join(tmp, 'LICENSE'), join(dest, 'LICENSE'))
    writeFileSync(join(dest, 'PINNED_COMMIT'), `${commit}\n`)
    writeFileSync(
      join(dest, 'SOURCE.md'),
      [
        '# Lapwing dictionary (vendored)',
        '',
        `- Upstream: ${UPSTREAM_URL}`,
        `- Commit: ${commit}`,
        '- License: MIT (see LICENSE)',
        '- Files: plover_lapwing/dictionaries/' + DICTIONARY_FILES.join(', '),
        '',
        'This directory is generated by `npm run sync:dictionary`; do not edit by hand.',
        '',
      ].join('\n'),
    )
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}

if (import.meta.main) {
  const commit = process.argv[2] ?? DEFAULT_COMMIT
  syncDictionary(commit)
  console.log(`Vendored ${UPSTREAM_URL}@${commit} into ${dest}`)
}
