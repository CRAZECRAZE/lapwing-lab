import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

export const UPSTREAM_URL = 'https://github.com/aerickt/lapwing-for-beginners'
export const DEFAULT_COMMIT = '46b53e1ebec3b19fb402da046d6dc0a13b530787'

const root = join(import.meta.dirname, '..')
const dest = join(root, 'content', 'lapwing-book')

function git(cwd: string, ...args: string[]): void {
  execFileSync('git', args, { cwd, stdio: 'inherit' })
}

export function syncBook(commit: string = DEFAULT_COMMIT): void {
  if (!/^[0-9a-f]{40}$/.test(commit)) {
    throw new Error(`Expected a full 40-hex commit hash, got "${commit}"`)
  }
  const tmp = mkdtempSync(join(tmpdir(), 'lapwing-book-'))
  try {
    git(tmp, 'init', '--quiet')
    git(tmp, 'fetch', '--quiet', '--depth', '1', UPSTREAM_URL, commit)
    git(tmp, '-c', 'advice.detachedHead=false', 'checkout', '--quiet', 'FETCH_HEAD')

    rmSync(dest, { recursive: true, force: true })
    mkdirSync(dest, { recursive: true })
    cpSync(join(tmp, 'src'), join(dest, 'src'), { recursive: true })
    cpSync(join(tmp, 'LICENSE'), join(dest, 'LICENSE'))
    writeFileSync(join(dest, 'PINNED_COMMIT'), `${commit}\n`)
    writeFileSync(
      join(dest, 'SOURCE.md'),
      [
        '# Lapwing for Beginners (vendored)',
        '',
        `- Upstream: ${UPSTREAM_URL}`,
        `- Commit: ${commit}`,
        '- License: GPL-3.0 (see LICENSE)',
        '',
        'This directory is generated by `npm run sync:book`; do not edit by hand.',
        'Do not redistribute without honoring the GPL.',
        '',
      ].join('\n'),
    )
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}

if (import.meta.main) {
  const commit = process.argv[2] ?? DEFAULT_COMMIT
  syncBook(commit)
  console.log(`Vendored ${UPSTREAM_URL}@${commit} into ${dest}`)
}
